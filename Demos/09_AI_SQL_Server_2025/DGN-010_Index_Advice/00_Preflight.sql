SET NOCOUNT ON;
DECLARE @Major int=TRY_CONVERT(int,SERVERPROPERTY('ProductMajorVersion')),
 @Build nvarchar(80)=CONVERT(nvarchar(80),SERVERPROPERTY('ProductVersion')),
 @Engine int=TRY_CONVERT(int,SERVERPROPERTY('EngineEdition')),
 @Edition int=TRY_CONVERT(int,SERVERPROPERTY('EditionID'));
IF @Major IN(15,16) BEGIN SELECT 'SQLPERF_SUMMARY|SKIP|SKIP_VERSION'; RETURN; END;
IF @Major IS NULL OR @Build IS NULL OR @Major<>17 OR @Build<>N'17.0.5005.3'
BEGIN SELECT 'SQLPERF_SUMMARY|SKIP|SKIP_CONFIGURATION'; RETURN; END;
IF @Engine IS NULL OR @Edition IS NULL OR @Engine<>3 OR @Edition<>-2117995310
BEGIN SELECT 'SQLPERF_SUMMARY|SKIP|SKIP_CONFIGURATION'; RETURN; END;
IF $(ConfirmIsolatedLab)<>1 OR $(HighImpactConfirmed)<>1
 THROW 51000,'FAIL_SAFETY: Bestaetigtes isoliertes Lastlab erforderlich.',1;
IF IS_SRVROLEMEMBER(N'sysadmin') IS NULL OR IS_SRVROLEMEMBER(N'sysadmin')<>1
BEGIN SELECT 'SQLPERF_SUMMARY|SKIP|SKIP_PERMISSION'; RETURN; END;
IF DB_ID(N'SQLPERF_LAB_DGN010_LOCAL') IS NOT NULL
 THROW 51004,'FAIL_STATE: Vorhandene Datenbank wird nicht uebernommen.',1;
SELECT CONCAT('DGN010_ENV|',@Major,'|',@Build,'|',@Engine,'|',@Edition);
SELECT 'SQLPERF_SUMMARY|PASS|OK';
