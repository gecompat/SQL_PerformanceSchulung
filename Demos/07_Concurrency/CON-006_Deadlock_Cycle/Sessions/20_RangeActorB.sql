SET NOCOUNT ON;SET XACT_ABORT ON;SET DEADLOCK_PRIORITY HIGH;
UPDATE lab.RangeActors SET SessionId=@@SPID,StartedAtUtc=SYSUTCDATETIME() WHERE RoleName='ACTOR_B';
EXEC fwk.USP_Signal '$(DemoId)','$(RunToken)','B_RANGE_ACTOR_READY';
BEGIN TRY
    SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;BEGIN TRAN;
    SELECT KeyValue FROM lab.RangeRows WITH(INDEX(PK_RangeRows),FORCESEEK) WHERE KeyValue>60 AND KeyValue<80;
    EXEC fwk.USP_WaitForSignal '$(DemoId)','$(RunToken)','B_INSERT_GRANTED',12000;
    INSERT lab.RangeRows(KeyValue)VALUES(30);
    COMMIT;
    UPDATE lab.RangeActors SET Outcome='SURVIVOR',ErrorNumber=NULL,FinishedAtUtc=SYSUTCDATETIME() WHERE RoleName='ACTOR_B';
END TRY
BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK;
    IF ERROR_NUMBER()<>1205 THROW;
    UPDATE lab.RangeActors SET Outcome='VICTIM',ErrorNumber=1205,FinishedAtUtc=SYSUTCDATETIME() WHERE RoleName='ACTOR_B';
END CATCH;
EXEC fwk.USP_Signal '$(DemoId)','$(RunToken)','B_RANGE_DONE';
